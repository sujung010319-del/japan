    ws.cell(note_row, 1).font = Font(FONT, size=9, italic=True, color="808080")
    ws.cell(note_row + 1, 1, "※ 자료: THE BIO 보도 표. 환율·집계 시점 차이로 만달러 금액과 억원 금액이 정확히 비례하지 않는 건이 있음(원문 그대로 기재).")
    ws.cell(note_row + 1, 1).font = Font(FONT, size=9, italic=True, color="808080")

    ws.freeze_panes = "C3"
    ws.auto_filter.ref = f"A2:{get_column_letter(len(cols))}{last}"
    return ws


